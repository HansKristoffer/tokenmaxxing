// Renders the prestige 3D showcase (tracks' full sets, pet wear, trophies) to PNGs in headless Chromium.
//   bunx bun@1.4.4 scripts/qa/prestige-3d/shots.mjs [--out /tmp/prestige/shots/3d]
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const arg = (k, d) => {
  const i = process.argv.indexOf(`--${k}`);
  return i > 0 ? process.argv[i + 1] : d;
};
const out = arg("out", "/tmp/prestige/shots/3d");
mkdirSync(out, { recursive: true });

// Pet wear and trophies are written by other hands: use them if they exist and export what we call.
const petFile = join(root, "web/src/render3d/pets/prestige-petwear3d.ts");
const trophyFile = join(root, "web/src/render3d/furniture/prestige3d.ts");
const optional = join(here, "optional.ts");
writeFileSync(
  optional,
  `// Generated by shots.mjs; not committed.
${existsSync(petFile) ? `import * as pw from "${petFile}";` : "const pw = {} as Record<string, unknown>;"}
${existsSync(trophyFile) ? `import * as tr from "${trophyFile}";` : "const tr = {} as Record<string, unknown>;"}
import type * as THREE from "three";
export function optionalPetwear(rank: number, neckR: number): THREE.Object3D | null {
  const f = (pw as any).petwear3d;
  return typeof f === "function" ? (f(rank, neckR) as THREE.Object3D) : null;
}
export function optionalTrophy(rank: number): THREE.Object3D | null {
  const f = (tr as any).prestigeTrophy3d;
  return typeof f === "function" ? (f(rank) as THREE.Object3D) : null;
}
`,
);

const built = await Bun.build({
  entrypoints: [join(here, "harness.ts")],
  target: "browser",
  format: "iife",
  // `three` lives in web/node_modules, out of reach of files under scripts/.
  plugins: [
    {
      name: "web-deps",
      setup(b) {
        b.onResolve({ filter: /^three(\/|$)/ }, (a) => ({
          path: Bun.resolveSync(a.path, join(root, "web/src/render3d/kit")),
        }));
      },
    },
  ],
  define: { "process.env.NODE_ENV": '"production"' },
});
rmSync(optional, { force: true });
if (!built.success) {
  console.error(built.logs.join("\n"));
  process.exit(1);
}
const js = await built.outputs[0].text();
const tmp = join(out, ".harness");
rmSync(tmp, { recursive: true, force: true });
mkdirSync(tmp, { recursive: true });
writeFileSync(
  join(tmp, "index.html"),
  `<!doctype html><meta charset=utf-8><body style="margin:0;background:#111"><script>${js.replaceAll("</script", "<\\/script")}</script>`,
);

const pw = await import(
  process.env.PLAYWRIGHT ?? "/Users/nicholaserlin/Desktop/YeetBudget/node_modules/playwright/index.mjs"
);
const browser = await pw.chromium.launch({
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"],
});
const page = await browser.newPage({ viewport: { width: 1800, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto(`file://${join(tmp, "index.html")}`);
await page.waitForFunction(() => document.title === "ready", null, { timeout: 90000 }).catch(() => {});
for (const id of await page.$$eval("canvas[id^=sheet-]", (cs) => cs.map((c) => c.id))) {
  const file = join(out, `${id.replace("sheet-", "")}.png`);
  await page.locator(`#${id}`).screenshot({ path: file });
  console.log(file);
}
await browser.close();
rmSync(tmp, { recursive: true, force: true });
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
